# Funções
a = 6
b = 3

# SOMA
def somar(a, b):
    return a + b

# SUBTRAÇÃO
def subtrair(a, b):
    return a - b

# MULTIPLICAÇÃO
def multiplicar(a, b):
    return a * b

# DIVISÃO
def dividir(a, b):
    return a / b

print(f"Numeros calculados: {a} e {b}")

print(f"Soma: {somar(a, b)}")
print(f"Subtração: {subtrair(a, b)}")
print(f"Multiplicação: {multiplicar(a, b)}")
print(f"Divisão: {dividir(a, b)}")